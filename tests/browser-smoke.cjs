const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = path.resolve(root, 'tmp/browser-checks');
fs.mkdirSync(out, {recursive:true});
let auditBrowser;
const mime = {'.html':'text/html','.css':'text/css','.js':'text/javascript','.jpg':'image/jpeg','.jpeg':'image/jpeg','.png':'image/png','.woff2':'font/woff2','.svg':'image/svg+xml'};
(async () => {
 const browser = auditBrowser = await chromium.launch({headless:true});
 const results = {desktop:[], mobile:[], interactions:[], errors:[]};
 const pages = fs.readdirSync(root).filter(file=>file.endsWith('.html')&&file!=='menu.html').concat('alpha-site-scorer/index.html');
 for (const [mode,opts] of [['desktop',{viewport:{width:1280,height:900}}],['mobile',{viewport:{width:390,height:844},isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1'}]]) {
  const context = await browser.newContext(opts);
  await context.route('https://portfolio.test/**',async route=>{
   const relative=decodeURIComponent(new URL(route.request().url()).pathname).replace(/^\//,'')||'index.html';
   const filename=path.resolve(root,relative.endsWith('/')?relative+'index.html':relative);
   if(!filename.startsWith(root+'/'))return route.abort();
   if(!fs.existsSync(filename))return route.fulfill({status:404,path:path.join(root,'404.html'),contentType:'text/html'});
   return route.fulfill({status:200,path:filename,contentType:mime[path.extname(filename)]||'application/octet-stream'});
  });
  await context.route('https://*.tile.openstreetmap.org/**',route=>route.abort());
  const page=await context.newPage();
  page.on('pageerror',error=>results.errors.push({mode,message:error.message}));
  for(const file of pages){
   await page.goto('https://portfolio.test/'+file,{waitUntil:'load'});
   await page.waitForFunction(()=>!document.body.classList.contains('is-preload'));
   await page.evaluate(()=>document.fonts.ready);
   await page.waitForFunction(()=>[...document.querySelectorAll('.tiles article, .card .score')].every(element=>Number(getComputedStyle(element).opacity)>=0.999));
   const info=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,title:document.title,brokenImages:[...document.images].filter(i=>!i.loading||i.loading!=='lazy').filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src),font:getComputedStyle(document.querySelector('h1')).fontFamily}));
   assert.ok(info.scrollWidth<=info.width+1,`${mode}/${file} overflows: ${info.scrollWidth}/${info.width}`);
   assert.equal(info.brokenImages.length,0,`${mode}/${file} has broken images`);
   assert.match(info.font,/Source Sans Pro/);
   results[mode].push({file,...info});
   if(file==='index.html'||file==='future-signal.html'||file==='alpha-site-scorer/index.html')await page.screenshot({path:path.join(out,`portfolio-preview-${mode}-${file==='index.html'?'home':file.startsWith('alpha-')?'alpha':'future'}.png`),fullPage:true});
  }
  await page.goto('https://portfolio.test/');
  await page.waitForFunction(()=>!document.body.classList.contains('is-preload'));
  await page.getByRole('link',{name:'Menu',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#menu').contains(document.activeElement));
  assert.equal(await page.evaluate(()=>document.querySelector('#wrapper').inert),true);
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Home');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Close');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Home');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Menu');
  assert.equal(await page.getByRole('link',{name:'Menu',exact:true}).getAttribute('aria-expanded'),'false');
  assert.equal(await page.evaluate(()=>document.querySelector('#wrapper').inert),false);
  results.interactions.push(mode+': menu focus, Tab wrapping, Escape and focus restoration passed');
  await page.goto('https://portfolio.test/alpha-site-scorer/');
  await page.getByRole('button',{name:'+ Add New Site',exact:true}).click();
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('Unsaved browser draft');
  assert.equal(await page.locator('#grid article').count(),15);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>localStorage.getItem('alpha-sites')),null);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'add-site');
  await page.getByRole('button',{name:'+ Add New Site',exact:true}).click();
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('Saved browser draft');
  await page.getByRole('textbox',{name:'Zip Code',exact:true}).fill('90210');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  assert.equal(await page.locator('#grid article').count(),16);
  await page.getByRole('button',{name:'Map',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#map-status').textContent.includes('Showing 15 of 16'));
  await page.getByRole('button',{name:'Cards',exact:true}).click();
  await page.getByRole('button',{name:'📊 Cost Breakdown',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('#costModal').getAttribute('aria-hidden')==='false');
  assert.equal(await page.locator('#costModal canvas').evaluate(canvas=>canvas.width>0&&canvas.height>0),true);
  assert.equal(await page.evaluate(()=>Boolean(Chart.getChart(document.querySelector('#costChart')))),true);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Kanban',exact:true}).click();
  await page.locator('.kanban-card').first().focus();
  await page.keyboard.press('Enter');
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('Edited from Kanban');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  assert.ok(await page.getByRole('button',{name:'Edit Edited from Kanban',exact:true}).count());
  results.interactions.push(mode+': Alpha draft/save/keyboard edit, chart and omitted-map count passed');
  await page.goto('https://portfolio.test/basketball_snake.html');
  await page.getByRole('button',{name:'How to Play',exact:true}).click();
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#countdown').isVisible(),false);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Start Game',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#pauseButton').getAttribute('aria-label')==='Pause Game'&&!document.querySelector('#pauseButton').classList.contains('hidden'));
  await page.keyboard.press('p');
  assert.equal(await page.getByRole('button',{name:'Resume Game',exact:true}).count(),1);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'gameCanvas');
  results.interactions.push(mode+': Snake Help isolation, start, keyboard pause and court focus passed');
  await context.close();
 }
 assert.equal(results.errors.length,0,JSON.stringify(results.errors));
 fs.writeFileSync(path.join(out,'portfolio-browser-verification.json'),JSON.stringify(results,null,2));
 console.log(JSON.stringify({desktopPages:results.desktop.length,mobilePages:results.mobile.length,interactions:results.interactions,errors:results.errors},null,2));
 await browser.close();
})().catch(async error=>{console.error(error.stack);if(auditBrowser)await auditBrowser.close();process.exitCode=1;});
